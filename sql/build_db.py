"""Build tenders.db from data/tender_dataset.csv and run every query in
02_analysis.sql, writing the outputs to sql/results.md.

Usage (from the repo root):  python sql/build_db.py
Needs only the Python standard library.
"""
import csv
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SQL_DIR = ROOT / "sql"
DB_PATH = SQL_DIR / "tenders.db"
CSV_PATH = ROOT / "data" / "tender_dataset.csv"

INT_COLS = {"Tender_Value_IDR", "Our_Bid_IDR", "Lead_Time_Days", "Quotation_Revisions"}
REAL_COLS = {"Bid_Margin_Pct"}


def convert(col, value):
    if col in INT_COLS:
        return int(value)
    if col in REAL_COLS:
        return float(value)  # CSV uses '.' as decimal separator
    return value


def build(con):
    con.executescript((SQL_DIR / "01_schema.sql").read_text(encoding="utf-8"))
    with open(CSV_PATH, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        rows = [[convert(c, r[c]) for c in reader.fieldnames] for r in reader]
    con.executemany(f"INSERT INTO tenders VALUES ({','.join('?' * 18)})", rows)
    con.commit()
    return len(rows)


def split_queries(text):
    """Return (title, sql) pairs; a query starts at a '-- Qn.' comment."""
    blocks = re.split(r"\n(?=-- Q\d+\.)", text)
    out = []
    for b in blocks:
        m = re.match(r"-- (Q\d+\..*)", b)
        if not m:
            continue
        sql = "\n".join(l for l in b.splitlines() if not l.strip().startswith("--")).strip()
        out.append((m.group(1).strip(), sql))
    return out


def to_markdown(cur):
    headers = [d[0] for d in cur.description]
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for row in cur.fetchall():
        lines.append("| " + " | ".join("" if v is None else str(v) for v in row) + " |")
    return "\n".join(lines)


def main():
    if DB_PATH.exists():
        DB_PATH.unlink()
    con = sqlite3.connect(DB_PATH)
    n = build(con)
    md = [f"# Query results\n\nGenerated by `build_db.py` from {n} tender records (synthetic dataset).\n"]
    for title, sql in split_queries((SQL_DIR / "02_analysis.sql").read_text(encoding="utf-8")):
        md.append(f"## {title}\n\n{to_markdown(con.execute(sql))}\n")
    (SQL_DIR / "results.md").write_text("\n".join(md), encoding="utf-8")
    print(f"Loaded {n} rows into {DB_PATH.name}; results written to sql/results.md")


if __name__ == "__main__":
    main()
